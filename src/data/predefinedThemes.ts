export function convertPaletteToCustomTheme(item: ColorPaletteItem, isActive = false): CustomTheme {
  const isLight = item.colors.background.toLowerCase().startsWith('#f') || item.colors.background.toLowerCase() === '#ffffff';

  return {
    id: item.id,
    name: item.name,
    description: item.description,
    preset: item.preset,
    isActive,
    isCustom: false,
    primaryColor: item.colors.primary,
    secondaryColor: item.colors.secondary,
    accentColor: item.colors.accent,
    backgroundColor: item.colors.background,
    cardBackgroundColor: item.cardBackgroundColor || (isLight ? '#ffffff' : '#12141c'),
    headerBackgroundColor: item.headerBackgroundColor || (isLight ? '#ffffff' : '#0f1015'),
    footerBackgroundColor: item.footerBackgroundColor || (isLight ? item.colors.secondary : '#090a0d'),
    buttonColor: item.buttonColor || item.colors.primary,
    buttonHoverColor: item.buttonHoverColor || item.colors.accent,
    textColor: item.textColor || (isLight ? '#0f172a' : '#f4f4f5'),
    secondaryTextColor: item.secondaryTextColor || (isLight ? '#475569' : '#9ca3af'),
    borderColor: item.borderColor || (isLight ? '#e2e8f0' : '#27272a'),
    inputBackgroundColor: item.inputBackgroundColor || (isLight ? '#ffffff' : '#18181b'),
    modalBackgroundColor: item.modalBackgroundColor || (isLight ? '#ffffff' : '#12141c'),
    successColor: item.successColor || '#10b981',
    warningColor: item.warningColor || '#f59e0b',
    errorColor: item.errorColor || '#f43f5e',
    borderRadius: item.borderRadius || '1rem',
    fontFamily: item.fontFamily || 'outfit',
    shadowLevel: item.shadowLevel || 'medium',
    backgrounds: {
      desktopBackground: '',
      tabletBackground: '',
      mobileBackground: '',
      loginBackground: '',
      adminBackground: '',
      homepageBackground: '',
      contestantSectionBackground: '',
      resultsBackground: '',
      footerBackground: '',
    },
    gradients: {
      heroGradient: '',
      headerGradient: '',
      buttonGradient: '',
      cardGradient: '',
      backgroundGradient: '',
      footerGradient: '',
      sectionGradient: '',
    },
  };
}
